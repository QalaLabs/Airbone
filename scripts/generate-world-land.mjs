// Regenerates src/lib/worldLand.js — the land outline behind the homepage route
// map — from Natural Earth 1:110m land (public domain) as packaged in
// world-atlas@2 (ISC). No runtime dependency; run once when the source changes:
//
//   npm pack world-atlas@2 && tar -xzf world-atlas-2.0.2.tgz
//   node scripts/generate-world-land.mjs package/land-110m.json
//
// Projection is the same equirectangular mapping the markers use (lib/routeMap.js).
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { project } from '../src/lib/routeMap.js'

const input = process.argv[2]
if (!input) {
  console.error('usage: node scripts/generate-world-land.mjs <land-110m.json>')
  process.exit(1)
}
const topo = JSON.parse(readFileSync(input, 'utf8'))
const { scale, translate } = topo.transform

const arcs = topo.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
  })
})

function ring(indexes) {
  const points = []
  for (const i of indexes) {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i]
    points.push(...(points.length ? arc.slice(1) : arc))
  }
  return points
}

const MIN_STEP = 0.8 // viewBox units; finer detail is invisible at this size
const subpaths = []
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs
  for (const polygon of polygons) {
    for (const r of polygon) {
      const lonlat = ring(r)
      if (lonlat.every(([, lat]) => lat < -60)) continue // Antarctica is outside the framed area
      const pts = []
      for (const [lon, lat] of lonlat) {
        const { x, y } = project(lat, lon)
        const p = [Math.round(x * 10) / 10, Math.round(y * 10) / 10]
        const last = pts[pts.length - 1]
        if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= MIN_STEP) pts.push(p)
      }
      if (pts.length < 4) continue
      const area = Math.abs(pts.reduce((a, [x1, y1], i) => {
        const [x2, y2] = pts[(i + 1) % pts.length]
        return a + (x1 * y2 - x2 * y1)
      }, 0)) / 2
      if (area < 1.5) continue
      subpaths.push(`M${pts.map(([x, y]) => `${x},${y}`).join('L')}Z`)
    }
  }
}

const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'worldLand.js')
writeFileSync(
  out,
  `// GENERATED by scripts/generate-world-land.mjs from Natural Earth 1:110m land
// (public domain, via world-atlas@2). Equirectangular, viewBox 0 0 1000 500. Do not edit.
export const WORLD_LAND_PATH =
  '${subpaths.join('')}'
`,
)
console.log(`wrote ${out}: ${subpaths.length} rings`)
